"""FCP7 XML exchange and generated After Effects composition scripts."""
from __future__ import annotations

import json
from pathlib import Path
import xml.etree.ElementTree as ET

from .media import absolute_path, atomic_bytes, write_json
from .media import FXError
from .plan import validate


def node(parent, tag, value=None):
    result = ET.SubElement(parent, tag)
    if value is not None:
        result.text = str(value)
    return result


def export(plan: dict, clips: list[Path], folder: Path, master: Path) -> dict:
    validate(plan)
    if len(clips) != len(plan["clips"]):
        raise FXError("Handoff clip count does not match the validated timeline")
    root = ET.Element("xmeml", version="5")
    sequence = node(root, "sequence")
    sequence.set("id", "autofx-sequence")
    node(sequence, "name", master.stem)
    node(sequence, "duration", plan["frames"])

    def rate(parent):
        result = node(parent, "rate")
        node(result, "timebase", plan["fps"])
        node(result, "ntsc", "FALSE")

    def video_format(parent):
        result = node(parent, "samplecharacteristics")
        rate(result)
        for key, value in {"width": plan["width"], "height": plan["height"],
                           "pixelaspectratio": "square", "fielddominance": "none",
                           "anamorphic": "FALSE"}.items():
            node(result, key, value)

    rate(sequence)
    media = node(sequence, "media")
    video = node(media, "video")
    video_format(node(video, "format"))
    video_track = node(video, "track")

    def add_clip(track, path, start, frames, identifier, kind):
        item = node(track, "clipitem")
        item.set("id", identifier)
        node(item, "name", path.name)
        node(item, "enabled", "TRUE")
        node(item, "duration", frames)
        rate(item)
        for key, value in {"start": start, "end": start + frames, "in": 0, "out": frames}.items():
            node(item, key, value)
        file = node(item, "file")
        file.set("id", identifier + "-file")
        node(file, "name", path.name)
        node(file, "pathurl", absolute_path(path).as_uri())
        node(file, "duration", frames)
        rate(file)
        fm = node(file, "media")
        if kind == "video":
            video_format(node(fm, "video"))
        else:
            audio = node(fm, "audio")
            node(audio, "channelcount", 2)
            sample = node(audio, "samplecharacteristics")
            node(sample, "samplerate", 48000)
            node(sample, "depth", 16)
        source_track = node(item, "sourcetrack")
        node(source_track, "mediatype", kind)
        node(source_track, "trackindex", 1)

    for i, (clip, path) in enumerate(zip(plan["clips"], clips)):
        add_clip(video_track, path, clip["timeline_frame"], clip["frames"], f"video-{i}", "video")
    audio = node(media, "audio")
    node(audio, "numOutputChannels", 2)
    # Split the complete stereo mix into two mono timeline tracks for FCP7 readers.
    for channel in (1, 2):
        track = node(audio, "track")
        add_clip(track, master, 0, plan["frames"], f"master-audio-{channel}", "audio")
        track.find("clipitem/sourcetrack/trackindex").text = str(channel)
    ET.indent(root)
    xml = folder / "timeline.xml"
    atomic_bytes(xml, ET.tostring(root, encoding="utf-8", xml_declaration=True))
    payload = {"name": "AutoFX", "fps": plan["fps"], "width": plan["width"],
               "height": plan["height"], "duration": plan["frames"] / plan["fps"],
               "master": str(master), "project": str(folder / "autofx.aep"),
               "clips": [{"path": str(path), "start": clip["timeline_frame"] / plan["fps"],
                          "duration": clip["frames"] / plan["fps"]}
                         for clip, path in zip(plan["clips"], clips)]}
    manifest = folder / "after_effects.json"
    write_json(manifest, payload)
    jsx = folder / "build_after_effects.jsx"
    atomic_bytes(jsx, build_jsx(payload).encode("utf-8"))
    return {"xml": str(xml), "after_effects_manifest": str(manifest),
            "after_effects_script": str(jsx)}


def build_jsx(payload: dict, status_path: Path | None = None) -> str:
    """JSON escaping keeps quotes, Unicode and path separators out of script syntax."""
    data = dict(payload, status=str(status_path) if status_path else None)
    template = r'''// Generated by AutoFX Studio. Open an EMPTY AE project first.
(function () {
    var d = __PAYLOAD__;
    function status(message) {
        if (!d.status) return;
        var f = new File(d.status);
        f.encoding = "UTF-8";
        if (!f.open("w")) throw new Error("Cannot write AutoFX status file");
        f.write(message);
        f.close();
    }
    var begun = false;
    try {
        if (app.project && app.project.numItems > 0)
            throw new Error("Open an empty AE project; existing work is preserved");
        if (new File(d.project).exists)
            throw new Error("Output AEP already exists; choose a new project path");
        app.beginUndoGroup("AutoFX import");
        begun = true;
        if (!app.project) app.newProject();
        var comp = app.project.items.addComp(d.name, d.width, d.height, 1, d.duration, d.fps);
        for (var i = 0; i < d.clips.length; i++) {
            var c = d.clips[i];
            var footage = app.project.importFile(new ImportOptions(new File(c.path)));
            var layer = comp.layers.add(footage);
            layer.startTime = c.start;
            layer.inPoint = c.start;
            layer.outPoint = c.start + c.duration;
            if (layer.hasAudio) layer.audioEnabled = false;
        }
        var mixed = app.project.importFile(new ImportOptions(new File(d.master)));
        var soundtrack = comp.layers.add(mixed);
        soundtrack.enabled = false;
        soundtrack.audioEnabled = true;
        app.project.save(new File(d.project));
        comp.openInViewer();
        status("OK\n" + d.project);
    } catch (error) {
        status("ERROR\n" + error.toString());
        throw error;
    } finally {
        if (begun) app.endUndoGroup();
    }
})();
'''
    return template.replace("__PAYLOAD__", json.dumps(data, ensure_ascii=True))
